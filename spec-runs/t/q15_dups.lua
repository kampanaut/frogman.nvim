local function step(label, fn)
	local ok, err = pcall(fn) vim.wait(150)
	print(string.format("  %-52s closed=[%s]%s", label, CLOSED(), ok and "" or ("  ERROR " .. tostring(err):sub(1, 90))))
end
step(":e a, :e b, :e c", function() vim.cmd('edit a.txt') vim.cmd('edit b.txt') vim.cmd('edit c.txt') end)
step(":bdelete a", function() vim.cmd('bdelete a.txt') end)
step(":e a  (reopen by hand)", function() vim.cmd('edit a.txt') end)
step(":e c, :bdelete a  (close it again)", function() vim.cmd('edit c.txt') vim.cmd('bdelete a.txt') end)
step(":bdelete b", function() vim.cmd('bdelete b.txt') end)
step("<M-S-w>  (reopen last closed)", function() CDV.reopen_last_closed() end)
step(":bdelete b  (close it again)", function() vim.cmd('edit c.txt') vim.cmd('bdelete b.txt') end)
step(":e d, :saveas x2.txt  (rename d)", function() vim.cmd('edit d.txt') vim.cmd('saveas x2.txt') end)
step(":saveas d.txt  (rename back)", function() vim.cmd('saveas! d.txt') end)
step(":file x3.txt, :file d.txt  (rename twice)", function() vim.cmd('file x3.txt') vim.cmd('file d.txt') end)
step(":e e, start cycling, :bdelete c, stop", function() vim.cmd('edit e.txt') CDV.cycle_left() vim.cmd('bdelete c.txt') CDV.cycle_select() end)
vim.cmd('qa!')
